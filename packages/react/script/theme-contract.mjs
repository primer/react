import fs from 'node:fs/promises'
import path from 'node:path'
import {createRequire} from 'node:module'

const require = createRequire(import.meta.url)
const primitives = path.dirname(require.resolve('@primer/primitives/package.json'))
const source = new URL('../src/', import.meta.url)
const used = new Set()

async function collect(directory) {
  for (const entry of await fs.readdir(directory, {withFileTypes: true})) {
    const filename = path.join(directory, entry.name)
    if (entry.isDirectory()) await collect(filename)
    else if (entry.name.endsWith('.module.css')) {
      const css = await fs.readFile(filename, 'utf8')
      for (const match of css.matchAll(/var\(--([\w-]+)/g)) used.add(match[1])
    }
  }
}

await collect(source.pathname)
const schemes = {}
let inputs
for (const scheme of ['light', 'dark']) {
  const docs = JSON.parse(
    await fs.readFile(path.join(primitives, `dist/docs/functional/themes/${scheme}.json`), 'utf8'),
  )
  const css = await fs.readFile(path.join(primitives, `dist/css/functional/themes/${scheme}.css`), 'utf8')
  const declarations = Object.fromEntries(
    [...css.matchAll(/--([\w-]+):\s*([^;]+);/g)].map(([, key, value]) => [key, value]),
  )
  const publicTokens = Object.values(docs).filter(
    token =>
      token.type === 'color' &&
      (/^(bgColor|fgColor|borderColor|control|focus)$/.test(token.path[0]) ||
        token.path.slice(0, 2).join('.') === 'button.primary'),
  )
  inputs ??= publicTokens.map(token => token.path.join('.')).sort()
  const publicNames = new Set(publicTokens.map(token => token.name))
  schemes[scheme] = {}
  for (const token of Object.values(docs)) {
    if (!publicNames.has(token.name) && !(used.has(token.name) && token.filePath.startsWith('src/tokens/component/'))) {
      continue
    }
    let value = declarations[token.name]
    if (!value) throw new Error(`Missing CSS declaration for ${scheme}: ${token.name}`)
    const reference = typeof token.original.$value === 'string' && token.original.$value.match(/^\{([^}]+)\}$/)
    if (reference && !reference[1].startsWith('base.')) {
      const alias = `var(--${reference[1].replaceAll('.', '-')})`
      value =
        token.alpha === undefined || token.alpha === 1
          ? alias
          : `color-mix(in srgb, ${alias} ${token.alpha * 100}%, transparent)`
    }
    schemes[scheme][`--${token.name}`] = value
  }
}
const typography = await fs.readFile(path.join(primitives, 'dist/css/functional/typography/typography.css'), 'utf8')
const shorthands = Object.fromEntries(
  [...typography.matchAll(/--(text-[\w-]*shorthand[\w-]*):\s*([^;]+);/g)].map(([, name, value]) => [
    `--${name}`,
    value,
  ]),
)
const header = '// Generated by node packages/react/script/theme-contract.mjs. Do not edit by hand.\n'
await fs.writeFile(
  new URL('../src/internal/theme/themeTokens.ts', import.meta.url),
  `${header}export const colorTokens = ${JSON.stringify(inputs)} as const\n` +
    `export const schemeTokens = ${JSON.stringify(schemes)}\n` +
    `export const typographyTokens = ${JSON.stringify(shorthands)}\n`,
)
