import {build} from 'esbuild'
import {readFile, writeFile} from 'node:fs/promises'
import {dirname, join, relative, resolve} from 'node:path'
import {fileURLToPath} from 'node:url'
import {format, resolveConfig} from 'prettier'

const directory = dirname(fileURLToPath(import.meta.url))
const root = resolve(directory, '../..')
const result = await build({
  absWorkingDir: root,
  entryPoints: [join(directory, 'panel.tsx')],
  outfile: join(directory, 'panel.js'),
  bundle: true,
  format: 'esm',
  target: 'chrome123',
  jsx: 'automatic',
  minify: true,
  legalComments: 'eof',
  loader: {'.woff2': 'file'},
  assetNames: 'assets/ui/[name]-[hash]',
  define: {'process.env.NODE_ENV': '"production"', __DEV__: 'false'},
  metafile: true,
})

for (const [file, parser, banner] of [
  ['panel.js', 'babel', '/* eslint-disable -- Generated by bundle-ui.mjs. */'],
  ['panel.css', 'css', '/* stylelint-disable -- Generated by bundle-ui.mjs. */'],
  ['catalog.json', 'json', ''],
]) {
  const path = join(directory, file)
  const options = await resolveConfig(path)
  await writeFile(path, await format(`${banner}\n${await readFile(path, 'utf8')}`, {...options, parser}))
}

const packages = new Set()
for (const output of Object.values(result.metafile.outputs)) {
  for (const [input, {bytesInOutput}] of Object.entries(output.inputs)) {
    if (!bytesInOutput || !input.startsWith('node_modules/')) continue
    const parts = input.split('/')
    packages.add(parts[1].startsWith('@') ? parts.slice(0, 3).join('/') : parts.slice(0, 2).join('/'))
  }
}
const notices = [await readFile(join(root, 'LICENSE'), 'utf8')]
for (const dependency of [...packages].sort()) {
  const path = join(root, dependency)
  const metadata = JSON.parse(await readFile(join(path, 'package.json'), 'utf8'))
  const candidates = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md', 'license.txt', 'LICENSE-MIT']
  let license
  for (const candidate of candidates) {
    try {
      license = await readFile(join(path, candidate), 'utf8')
      break
    } catch (error) {
      if (error.code !== 'ENOENT') throw error
    }
  }
  if (!license && metadata.name === '@primer/live-region-element') {
    license = await readFile(new URL('assets/licenses/live-region-element-LICENSE.txt', import.meta.url), 'utf8')
  }
  if (!license) throw new Error(`Missing license for bundled dependency ${metadata.name}.`)
  notices.push(`${metadata.name} ${metadata.version}\n${license}`)
}
await writeFile(join(directory, 'assets/ui-LICENSES.txt'), notices.join('\n\n--------------------\n\n'))
console.log(`Bundled the shared Primer sidebar into ${relative(root, directory)} (no repository build).`)
